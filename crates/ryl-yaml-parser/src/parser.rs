impl<'input, T: BorrowedInput<'input>, O: crate::TokenObserver> Parser<'input, T, O> {
    /// Return the next anchor ID that will be assigned by this parser.
    #[must_use]
    pub fn anchor_offset(&self) -> usize {
        self.anchor_id_count
    }

    /// Set the next anchor ID that will be assigned by this parser.
    pub fn set_anchor_offset(&mut self, offset: usize) {
        self.anchor_id_count = offset;
    }

    /// Observe each emitted scanner token once, including comments and stream end.
    ///
    /// Payloads borrow scanner storage only for the callback; parser errors may stop
    /// observation before stream end, and peeking never repeats a callback.
    #[must_use]
    pub fn with_options_and_observer(src: T, options: Options, observer: O) -> Self {
        let max_buffered_comment_events = options.max_buffered_comment_events;
        let block_nesting_limit = options.block_nesting_limit;
        let scanner = Scanner::with_options(src, options);

        Parser {
            observer,
            scanner,
            max_buffered_comment_events,
            block_nesting_limit,
            block_level: 0,
            states: Vec::new(),
            state: State::StreamStart,
            token: None,
            current: None,
            current_error: None,
            deferred_error: None,
            queued_events: VecDeque::new(),

            pending_key_indent: None,
            pending_node_anchor_id: 0,
            pending_node_tag: None,
            pending_node_tag_start: None,
            pending_node_property_end: None,
            pending_empty_scalar_span: None,
            last_non_comment_event_end: None,
            pending_document_version: None,
            pending_document_directives: false,
            pending_document_tag_handles: BTreeSet::new(),

            anchors: BTreeMap::new(),
            // valid anchor_id starts from 1
            anchor_id_count: 1,
            tags: BTreeMap::new(),
            stream_end_emitted: false,
            keep_tags: false,
        }
    }

    /// Configure whether tag directives remain active across document boundaries.
    ///
    /// This behavior is non-standard as per the YAML specification but can be encountered in the
    /// wild. Passing `true` enables this non-standard extension and allows the parser to accept
    /// input from [test
    /// QLJ7](https://github.com/yaml/yaml-test-suite/blob/ccfa74e56afb53da960847ff6e6976c0a0825709/src/QLJ7.yaml)
    /// of the yaml-test-suite:
    ///
    /// ```yaml
    /// %TAG !prefix! tag:example.com,2011:
    /// --- !prefix!A
    /// a: b
    /// --- !prefix!B
    /// c: d
    /// --- !prefix!C
    /// e: f
    /// ```
    ///
    /// With `keep_tags` set to `false`, the above YAML is rejected. As per the specification, tags
    /// only apply to the document immediately following them. This would error on `!prefix!B`.
    ///
    /// With `keep_tags` set to `true`, the above YAML is accepted by the parser.
    #[must_use]
    pub fn keep_tags(mut self, value: bool) -> Self {
        self.keep_tags = value;
        self
    }

    /// Try to load the next event and return it without consuming it from `self`.
    ///
    /// Any subsequent call to [`Parser::peek`] will return the same value, until a call to
    /// [`Iterator::next`] or [`Parser::load`].
    /// If the buffered value is a [`ScanError`], [`Parser::next_event`] returns that error once
    /// and then the parser is exhausted.
    ///
    /// # Errors
    /// Returns `ScanError` when loading the next event fails.
    pub fn peek(&mut self) -> Option<Result<&(Event<'input>, Span), ScanError>> {
        ParserTrait::peek(self)
    }

    /// Try to load the next event and return it, consuming it from `self`.
    ///
    /// After this returns a [`ScanError`], subsequent calls return [`None`].
    ///
    /// # Errors
    /// Returns `ScanError` when loading the next event fails.
    pub fn next_event(&mut self) -> Option<ParseResult<'input>> {
        ParserTrait::next_event(self)
    }

    /// Implementation function for [`Self::next_event`] without the `Option`.
    ///
    /// [`Self::next_event`] should conform to the expectations of an [`Iterator`] and return an
    /// option. This burdens the parser code. This function is used internally when an option is
    /// undesirable.
    fn next_event_impl<'a>(&mut self) -> ParseResult<'a>
    where
        'input: 'a,
    {
        let event = match self.current.take() {
            None => {
                if let Some(event) = self.queued_events.pop_front() {
                    Ok(self.apply_pending_key_indent(event))
                } else if let Some(error) = self.deferred_error.take() {
                    return Err(error);
                } else if self.state != State::End
                    && let Some(comment) = self.maybe_next_comment_event()?
                {
                    Ok(comment)
                } else {
                    self.parse()
                }
            }
            Some(v) => Ok(v),
        }?;

        Ok(self.remember_non_comment_event_end(event))
    }

    fn apply_pending_key_indent<'a>(
        &mut self,
        (ev, span): (Event<'a>, Span),
    ) -> (Event<'a>, Span) {
        if ev.is_node()
            && let Some(indent) = self.pending_key_indent.take()
        {
            return (ev, span.with_indent(Some(indent)));
        }

        (ev, span)
    }

    fn remember_non_comment_event_end<'a>(
        &mut self,
        (event, span): (Event<'a>, Span),
    ) -> (Event<'a>, Span) {
        if matches!(event, Event::Comment(..)) {
            return (event, span);
        }
        self.last_non_comment_event_end = Some(span.end);
        (event, span)
    }

    /// Peek at the next token from the scanner.
    fn peek_token(&mut self) -> Result<&QueuedToken<'_>, ScanError> {
        if let Some(error) = &self.deferred_error {
            return Err(error.clone());
        }

        match self.token {
            None => {
                self.token = Some(self.scan_next_token()?);
                Ok(self.token.as_ref().unwrap())
            }
            Some(ref tok) => Ok(tok),
        }
    }

    /// The token peeked before dispatch: every state handler is entered with the next token
    /// already peeked.
    fn peeked(&self) -> &QueuedToken<'input> {
        self.token
            .as_ref()
            .expect("the next token is peeked before state dispatch")
    }

    /// Take the peeked token when `accept` matches its type, leaving any other token peeked.
    fn take_peeked_if(
        &mut self,
        accept: impl FnOnce(&QueuedTokenType<'input>) -> bool,
    ) -> Option<QueuedToken<'input>> {
        if accept(&self.peeked().1) {
            self.token.take()
        } else {
            None
        }
    }

    /// Extract and return the next token from the scanner.
    ///
    /// This function does _not_ make use of `self.token`.
    fn scan_next_token(&mut self) -> Result<QueuedToken<'input>, ScanError> {
        let tok = self
            .scanner
            .next_queued_token()?
            .expect("scanner ended before the parser consumed its stream-end token");
        self.observer.on_token(&tok.0, tok.1.kind());
        Ok(tok)
    }

    #[inline]
    fn maybe_next_comment_event<'a>(
        &mut self,
    ) -> Result<Option<(Event<'a>, Span)>, ScanError>
    where
        'input: 'a,
    {
        if self.scanner.comments_possible() {
            self.next_comment_event()
        } else {
            self.peek_token()?;
            Ok(None)
        }
    }

    fn next_comment_event<'a>(&mut self) -> Result<Option<(Event<'a>, Span)>, ScanError>
    where
        'input: 'a,
    {
        self.peek_token()?;
        Ok(self.take_comment_event())
    }

    /// Take the peeked token as a comment event, if it is one.
    fn take_comment_event<'a>(&mut self) -> Option<(Event<'a>, Span)>
    where
        'input: 'a,
    {
        let Some(QueuedToken(span, QueuedTokenType::Comment(comment))) =
            self.take_peeked_if(|token| matches!(token, QueuedTokenType::Comment(_)))
        else {
            return None;
        };
        let placement = self.refined_comment_placement(span, comment.placement());
        Some((Event::Comment(comment.into_text(), placement), span))
    }

    #[inline]
    fn next_comment_events(&mut self) -> Result<Vec<(Event<'input>, Span)>, ScanError> {
        if !self.scanner.comments_possible() {
            return Ok(Vec::new());
        }

        let mut events = Vec::new();
        loop {
            match self.peek_token() {
                Ok(token) if matches!(token.1, QueuedTokenType::Comment(_)) => {}
                Err(error) if events.is_empty() => return Err(error),
                Err(error) => {
                    debug_assert!(self.deferred_error.is_none());
                    self.deferred_error = Some(error);
                    return Ok(events);
                }
                Ok(_) => return Ok(events),
            }

            if events.len() >= self.max_buffered_comment_events {
                return Err(ScanError::from_kind(
                    self.peeked().0.start,
                    ErrorKind::TooManyComments,
                ));
            }

            let comment = self
                .take_comment_event()
                .expect("comment token disappeared after peek");
            events.push(comment);
            if self.deferred_error.is_some() {
                return Ok(events);
            }
        }
    }

    fn queue_tail_and_return_first(
        &mut self,
        events: Vec<(Event<'input>, Span)>,
    ) -> (Event<'input>, Span) {
        let mut events = events.into_iter();
        let first = events
            .next()
            .expect("event queue must contain at least one event");
        self.queued_events.extend(events);
        first
    }

    fn queue_event_by_span(
        &mut self,
        comments: Vec<(Event<'input>, Span)>,
        event: (Event<'input>, Span),
    ) -> (Event<'input>, Span) {
        let insert_at = comments
            .iter()
            .position(|(_, comment_span)| {
                comment_span.start.index() >= event.1.start.index()
                    && comment_span.end.index() >= event.1.end.index()
            })
            .unwrap_or(comments.len());
        let mut ordered = Vec::with_capacity(comments.len() + 1);
        let mut comments = comments.into_iter();

        for _ in 0..insert_at {
            ordered.push(
                comments
                    .next()
                    .expect("comment disappeared while ordering queued events"),
            );
        }
        ordered.push(event);
        ordered.extend(comments);

        self.queue_tail_and_return_first(ordered)
    }

    fn queue_two_events_by_span(
        &mut self,
        comments: Vec<(Event<'input>, Span)>,
        first: (Event<'input>, Span),
        second: (Event<'input>, Span),
    ) -> (Event<'input>, Span) {
        let insert_at = comments
            .iter()
            .position(|(_, comment_span)| {
                comment_span.start.index() >= first.1.start.index()
                    && comment_span.end.index() >= first.1.end.index()
            })
            .unwrap_or(comments.len());
        let mut ordered = Vec::with_capacity(comments.len() + 2);
        let mut comments = comments.into_iter();

        for _ in 0..insert_at {
            ordered.push(
                comments
                    .next()
                    .expect("comment disappeared while ordering queued events"),
            );
        }
        ordered.push(first);
        ordered.push(second);
        ordered.extend(comments);

        self.queue_tail_and_return_first(ordered)
    }

    fn refined_comment_placement(
        &mut self,
        span: Span,
        placement: Placement,
    ) -> Placement {
        if placement == Placement::Right {
            return Placement::Right;
        }

        let next = match self.peek_token() {
            Ok(next) => next,
            Err(error) => {
                debug_assert!(self.deferred_error.is_none());
                self.deferred_error = Some(error);
                return placement;
            }
        };
        if matches!(next.1, QueuedTokenType::StreamEnd) {
            return Placement::Last;
        }

        if next.0.start.line() == span.end.line() + 1 {
            Placement::Above
        } else {
            Placement::Free
        }
    }

    /// Skip the next token from the scanner.
    fn skip(&mut self) {
        self.token = None;
    }
    /// Pops the top-most state and make it the current state.
    ///
    /// # Panics
    /// Panics if the state stack is empty.
    #[track_caller]
    fn pop_state(&mut self) {
        self.state = self.states.pop().unwrap();
    }
    /// Push a new state atop the state stack.
    fn push_state(&mut self, state: State) {
        self.states.push(state);
    }

    fn start_block_collection(&mut self, mark: Marker) -> Result<(), ScanError> {
        if self.block_level >= self.block_nesting_limit {
            return Err(ScanError::from_kind(
                mark,
                ErrorKind::RecursionLimitExceeded,
            ));
        }
        self.block_level += 1;
        Ok(())
    }

    fn end_block_collection(&mut self) {
        debug_assert!(self.block_level > 0);
        self.block_level -= 1;
    }

    fn defer_parse_node<'a>(
        &mut self,
        node_state: State,
        return_state: State,
        block: bool,
        indentless_sequence: bool,
    ) -> ParseResult<'a>
    where
        'input: 'a,
    {
        // Comments before a node were already emitted, so its first token is peeked.
        self.push_state(return_state);
        self.state = node_state;
        self.parse_node(block, indentless_sequence)
    }

    fn parse<'a>(&mut self) -> ParseResult<'a>
    where
        'input: 'a,
    {
        let event = self.state_machine()?;
        Ok(self.apply_pending_key_indent(event))
    }

    /// Load the YAML from the stream in `self`, pushing events into `recv`.
    ///
    /// The contents of the stream are parsed and the corresponding events are sent into the
    /// receiver. For detailed explanations about how events work, see [`EventReceiver`].
    ///
    /// If `multi` is set to `true`, the parser will allow parsing of multiple YAML documents
    /// inside the stream.
    ///
    /// Use this method when event handling is infallible. If receiver code can return an
    /// application error and should stop parsing, use [`Parser::try_load`] instead. If the caller
    /// should directly control when the next event is read, use [`Parser`]'s
    /// [`core::iter::Iterator`] implementation.
    ///
    /// Note that any [`EventReceiver`] is also a [`SpannedEventReceiver`], so implementing the
    /// former is enough to call this function.
    ///
    /// # Example
    /// ```
    /// # use ryl_yaml_parser::{Event, EventReceiver, Parser};
    /// # fn main() -> Result<(), ryl_yaml_parser::ScanError> {
    /// struct EventSink<'input> {
    ///     events: Vec<Event<'input>>,
    /// }
    ///
    /// impl<'input> EventReceiver<'input> for EventSink<'input> {
    ///     fn on_event(&mut self, ev: Event<'input>) {
    ///         self.events.push(ev);
    ///     }
    /// }
    ///
    /// let mut parser = Parser::new_from_str("a: 1\n");
    /// let mut sink = EventSink { events: Vec::new() };
    ///
    /// parser.load(&mut sink, false)?;
    ///
    /// assert!(sink
    ///     .events
    ///     .iter()
    ///     .any(|ev| matches!(ev, Event::Scalar(value, ..) if value == "a")));
    /// # Ok(())
    /// # }
    /// ```
    ///
    /// # Errors
    /// Returns `ScanError` when loading fails.
    pub fn load<R: SpannedEventReceiver<'input>>(
        &mut self,
        recv: &mut R,
        multi: bool,
    ) -> Result<(), ScanError> {
        ParserTrait::load(self, recv, multi)
    }

    /// Load the YAML from the stream in `self`, pushing events into `recv`.
    ///
    /// This is the fallible counterpart to [`Parser::load`]. If `recv` returns an error, parsing
    /// stops immediately and that error is returned as [`TryLoadError::Receiver`].
    ///
    /// If `multi` is set to `true`, the parser will allow parsing of multiple YAML documents
    /// inside the stream.
    ///
    /// If the receiver returns an error, the parser is left positioned immediately after the event
    /// that caused the receiver error. Callers should treat the parser as partially consumed.
    ///
    /// # Example
    /// ```
    /// # use ryl_yaml_parser::{Event, Parser, TryEventReceiver, TryLoadError};
    /// #[derive(Debug, PartialEq, Eq)]
    /// enum ValidationError {
    ///     ForbiddenScalar,
    /// }
    ///
    /// struct Validator;
    ///
    /// impl<'input> TryEventReceiver<'input> for Validator {
    ///     type Error = ValidationError;
    ///
    ///     fn on_event(&mut self, ev: Event<'input>) -> Result<(), Self::Error> {
    ///         if matches!(ev, Event::Scalar(value, ..) if value.as_ref() == "bad") {
    ///             Err(ValidationError::ForbiddenScalar)
    ///         } else {
    ///             Ok(())
    ///         }
    ///     }
    /// }
    ///
    /// let mut parser = Parser::new_from_str("value: bad\n");
    /// let mut validator = Validator;
    ///
    /// let err = parser.try_load(&mut validator, false).unwrap_err();
    ///
    /// assert_eq!(err, TryLoadError::Receiver(ValidationError::ForbiddenScalar));
    /// ```
    ///
    /// # Errors
    /// Returns [`TryLoadError::Scan`] when scanning or parsing the stream fails. Returns
    /// [`TryLoadError::Receiver`] when `recv` returns an error.
    pub fn try_load<R: TrySpannedEventReceiver<'input>>(
        &mut self,
        recv: &mut R,
        multi: bool,
    ) -> Result<(), TryLoadError<R::Error>> {
        ParserTrait::try_load(self, recv, multi)
    }

    fn state_machine<'a>(&mut self) -> ParseResult<'a>
    where
        'input: 'a,
    {
        match self.state {
            State::StreamStart => Ok(self.stream_start()),

            State::ImplicitDocumentStart => self.document_start(true),
            State::DocumentStart => self.document_start(false),
            State::DocumentContent => self.document_content(),
            State::DocumentEnd => self.document_end(),

            State::BlockNode => self.parse_node(true, false),
            State::BlockNodeOrIndentlessSequence => self.parse_node(true, true),
            State::FlowNode => self.parse_node(false, false),
            State::BlockMappingFirstKey => self.block_mapping_key(true),
            State::BlockMappingKey => self.block_mapping_key(false),
            State::BlockMappingKeyNode => self.block_mapping_key_node(),
            State::BlockMappingValue => self.block_mapping_value(),
            State::BlockMappingValueNode => self.block_mapping_value_node(),

            State::BlockSequenceFirstEntry => self.block_sequence_entry(true),
            State::BlockSequenceEntry => self.block_sequence_entry(false),
            State::BlockSequenceEntryNode => self.block_sequence_entry_node(),

            State::FlowSequenceFirstEntry => self.flow_sequence_entry(true),
            State::FlowSequenceEntry => self.flow_sequence_entry(false),

            State::FlowMappingFirstKey => self.flow_mapping_key(true),
            State::FlowMappingKey => self.flow_mapping_key(false),
            State::FlowMappingKeyNode => self.flow_mapping_key_node(),
            State::FlowMappingValue => self.flow_mapping_value(false),
            State::FlowMappingValueNode => self.flow_mapping_value_node(),

            State::IndentlessSequenceEntry => self.indentless_sequence_entry(),
            State::IndentlessSequenceEntryNode => self.indentless_sequence_entry_node(),

            State::FlowSequenceEntryMappingKey => {
                self.flow_sequence_entry_mapping_key()
            }
            State::FlowSequenceEntryMappingValue => {
                self.flow_sequence_entry_mapping_value()
            }
            State::FlowSequenceEntryMappingValueNode => {
                self.flow_sequence_entry_mapping_value_node()
            }
            State::FlowSequenceEntryMappingEnd => {
                self.flow_sequence_entry_mapping_end()
            }
            State::FlowMappingEmptyValue => self.flow_mapping_value(true),

            State::End => Ok((Event::StreamEnd, Span::empty(self.scanner.mark()))),
        }
    }

    fn stream_start<'a>(&mut self) -> (Event<'a>, Span)
    where
        'input: 'a,
    {
        // The scanner always emits `StreamStart` first.
        let QueuedToken(span, _) = *self.peeked();
        self.state = State::ImplicitDocumentStart;
        self.skip();
        (Event::StreamStart, span)
    }

    fn has_pending_document_directives(&self) -> bool {
        self.pending_document_directives
            || self.pending_document_version.is_some()
            || !self.pending_document_tag_handles.is_empty()
    }

    fn document_start<'a>(&mut self, implicit: bool) -> ParseResult<'a>
    where
        'input: 'a,
    {
        // Resume a document start paused to emit comments before handling markers that are only
        // ignorable between documents. In particular, `...` is invalid while `---` is still
        // required after directives and must not be consumed by the loop below.
        if self.has_pending_document_directives() {
            return self.explicit_document_start();
        }

        while let QueuedTokenType::DocumentEnd = self.peek_token()?.1 {
            self.skip();
        }

        // Anchors are scoped to a single document.
        self.anchors.clear();

        // Skipping a leading document-end marker can expose a comment that the normal
        // `next_event_impl` pre-dispatch check could not see yet. Emit it before deciding whether
        // another document starts; presentation-only comments must not create an implicit document.
        if let Some(comment) = self.maybe_next_comment_event()? {
            return Ok(comment);
        }

        match *self.peeked() {
            QueuedToken(span, QueuedTokenType::StreamEnd) => {
                self.state = State::End;
                self.skip();
                Ok((Event::StreamEnd, span))
            }
            QueuedToken(
                _,
                QueuedTokenType::VersionDirective(..)
                | QueuedTokenType::TagDirective(..)
                | QueuedTokenType::ReservedDirective(..)
                | QueuedTokenType::DocumentStart,
            ) => {
                // explicit document
                self.explicit_document_start()
            }
            QueuedToken(span, _) if implicit => {
                if !self.keep_tags {
                    self.tags.clear();
                }
                self.push_state(State::DocumentEnd);
                self.state = State::BlockNode;
                Ok((Event::DocumentStart(false, None), span))
            }
            _ => {
                // explicit document
                self.explicit_document_start()
            }
        }
    }

    fn parser_process_directives(
        &mut self,
        mut version: Option<YamlVersion>,
        continuing: bool,
        mut document_tag_handles: BTreeSet<Cow<'input, str>>,
    ) -> Result<(Option<YamlVersion>, BTreeSet<Cow<'input, str>>), ScanError> {
        let mut tags = if continuing || self.keep_tags {
            core::mem::take(&mut self.tags)
        } else {
            BTreeMap::new()
        };

        loop {
            self.peek_token()?;
            match self.token.take() {
                Some(QueuedToken(
                    span,
                    QueuedTokenType::VersionDirective(major, minor),
                )) => {
                    if version.is_some() {
                        return Err(ScanError::from_kind(
                            span.start,
                            ErrorKind::DuplicateVersionDirective,
                        ));
                    }
                    if major != 1 {
                        return Err(ScanError::from_kind(
                            span.start,
                            ErrorKind::UnsupportedYamlMajorVersion,
                        ));
                    }
                    version = Some(YamlVersion::new(major, minor));
                }
                Some(QueuedToken(
                    span,
                    QueuedTokenType::TagDirective(handle, prefix),
                )) => {
                    if !document_tag_handles.insert(handle.clone()) {
                        return Err(ScanError::from_kind(
                            span.start,
                            ErrorKind::DuplicateTagDirective,
                        ));
                    }
                    tags.insert(handle, prefix);
                }
                // Reserved directives are ignored.
                Some(QueuedToken(_, QueuedTokenType::ReservedDirective(..))) => {}
                other => {
                    self.token = other;
                    break;
                }
            }
        }

        self.tags = tags;
        Ok((version, document_tag_handles))
    }

    fn explicit_document_start<'a>(&mut self) -> ParseResult<'a>
    where
        'input: 'a,
    {
        let version = {
            let pending_version = self.pending_document_version.take();
            let continuing_directives =
                core::mem::take(&mut self.pending_document_directives);
            let pending_tag_handles =
                core::mem::take(&mut self.pending_document_tag_handles);
            let (version, document_tag_handles) = self.parser_process_directives(
                pending_version,
                continuing_directives,
                pending_tag_handles,
            )?;
            if let Some(comment) = self.maybe_next_comment_event()? {
                self.pending_document_version = version;
                self.pending_document_directives = true;
                self.pending_document_tag_handles = document_tag_handles;
                return Ok(comment);
            }
            version
        };
        match *self.peeked() {
            QueuedToken(mark, QueuedTokenType::DocumentStart) => {
                self.push_state(State::DocumentEnd);
                self.state = State::DocumentContent;
                self.skip();
                Ok((Event::DocumentStart(true, version), mark))
            }
            QueuedToken(span, _) => Err(ScanError::from_kind(
                span.start,
                ErrorKind::ExpectedDocumentStart,
            )),
        }
    }

    fn document_content<'a>(&mut self) -> ParseResult<'a>
    where
        'input: 'a,
    {
        if let QueuedToken(
            _,
            QueuedTokenType::VersionDirective(..)
            | QueuedTokenType::TagDirective(..)
            | QueuedTokenType::ReservedDirective(..)
            | QueuedTokenType::DocumentStart
            | QueuedTokenType::DocumentEnd
            | QueuedTokenType::StreamEnd,
        ) = *self.peeked()
        {
            self.pop_state();
            let end = self
                .last_non_comment_event_end
                .expect("a document start precedes its content");
            Ok((Event::empty_scalar(), Span::empty(end)))
        } else {
            self.state = State::BlockNode;
            self.parse_node(true, false)
        }
    }

    fn document_end<'a>(&mut self) -> ParseResult<'a>
    where
        'input: 'a,
    {
        let mut explicit_end = false;
        let span: Span = match *self.peeked() {
            QueuedToken(span, QueuedTokenType::DocumentEnd) => {
                explicit_end = true;
                self.skip();
                span
            }
            QueuedToken(..) => Span::empty(
                self.last_non_comment_event_end
                    .expect("a document's events precede its end"),
            ),
        };

        if self.keep_tags {
            // Never persist default handles across document boundaries. Allowing `%TAG !! ...`
            // or `%TAG ! ...` to leak into following documents lets earlier documents alter how
            // explicit tags are interpreted later on.
            self.tags.remove("!!");
            self.tags.remove("!");
        } else {
            self.tags.clear();
        }
        if explicit_end {
            self.state = State::ImplicitDocumentStart;
        } else {
            if let QueuedToken(
                span,
                QueuedTokenType::VersionDirective(..)
                | QueuedTokenType::TagDirective(..)
                | QueuedTokenType::ReservedDirective(..),
            ) = *self.peek_token()?
            {
                return Err(ScanError::from_kind(
                    span.start,
                    ErrorKind::MissingDocumentEndBeforeDirective,
                ));
            }
            self.state = State::DocumentStart;
        }

        Ok((Event::DocumentEnd, span))
    }

    fn register_anchor(
        &mut self,
        name: Cow<'input, str>,
        mark: &Span,
    ) -> Result<usize, ScanError> {
        // YAML permits anchor names to be reused. Aliases resolve to the most recent definition.
        let new_id = self.anchor_id_count;
        self.anchor_id_count =
            self.anchor_id_count.checked_add(1).ok_or_else(|| {
                ScanError::from_kind(mark.start, ErrorKind::AnchorCountOverflow)
            })?;
        self.anchors.insert(name, new_id);
        Ok(new_id)
    }

    fn save_pending_node_properties(
        &mut self,
        anchor_id: usize,
        tag: Option<Cow<'input, Tag>>,
        tag_start: Option<Marker>,
        property_end: Option<Marker>,
    ) {
        self.pending_node_anchor_id = anchor_id;
        self.pending_node_tag = tag;
        self.pending_node_tag_start = tag_start;
        self.pending_node_property_end = property_end;
    }

    fn attach_tag_start(
        event: Event<'_>,
        span: Span,
        start: Option<Marker>,
    ) -> (Event<'_>, Span) {
        (event, span.with_tag_start(start))
    }

    #[allow(clippy::too_many_lines)]
    fn parse_node<'a>(
        &mut self,
        block: bool,
        indentless_sequence: bool,
    ) -> ParseResult<'a>
    where
        'input: 'a,
    {
        let (mut anchor_id, mut tag, mut tag_start, mut property_end) = (
            core::mem::take(&mut self.pending_node_anchor_id),
            self.pending_node_tag.take(),
            self.pending_node_tag_start.take(),
            self.pending_node_property_end.take(),
        );
        if anchor_id == 0
            && tag.is_none()
            && let Some(QueuedToken(span, QueuedTokenType::Alias(name))) =
                self.take_peeked_if(|token| matches!(token, QueuedTokenType::Alias(_)))
        {
            self.pop_state();
            return match self.anchors.get(&*name) {
                None => Err(ScanError::from_kind(span.start, ErrorKind::UnknownAnchor)),
                Some(id) => Ok((Event::Alias(*id), span)),
            };
        }
        if anchor_id == 0
            && let Some(QueuedToken(span, QueuedTokenType::Anchor(name))) =
                self.take_peeked_if(|token| matches!(token, QueuedTokenType::Anchor(_)))
        {
            anchor_id = self.register_anchor(name, &span)?;
            property_end = Some(span.end);
            if tag.is_none() {
                self.peek_token()?;
                if let Some(QueuedToken(
                    tag_span,
                    QueuedTokenType::Tag(handle, suffix),
                )) = self
                    .take_peeked_if(|token| matches!(token, QueuedTokenType::Tag(..)))
                {
                    tag_start = Some(tag_span.start);
                    tag = Some(self.resolve_tag(tag_span, &handle, suffix)?);
                    property_end = Some(tag_span.end);
                }
            }
            if let Some(comment) = self.maybe_next_comment_event()? {
                self.save_pending_node_properties(
                    anchor_id,
                    tag,
                    tag_start,
                    property_end,
                );
                return Ok(comment);
            }
        } else if tag.is_none()
            && let Some(QueuedToken(mark, QueuedTokenType::Tag(handle, suffix))) =
                self.take_peeked_if(|token| matches!(token, QueuedTokenType::Tag(..)))
        {
            tag_start = Some(mark.start);
            property_end = Some(mark.end);
            tag = Some(self.resolve_tag(mark, &handle, suffix)?);
            if anchor_id == 0 {
                self.peek_token()?;
                if let Some(QueuedToken(mark, QueuedTokenType::Anchor(name))) = self
                    .take_peeked_if(|token| matches!(token, QueuedTokenType::Anchor(_)))
                {
                    anchor_id = self.register_anchor(name, &mark)?;
                    property_end = Some(mark.end);
                }
            }
            if let Some(comment) = self.maybe_next_comment_event()? {
                self.save_pending_node_properties(
                    anchor_id,
                    tag,
                    tag_start,
                    property_end,
                );
                return Ok(comment);
            }
        }
        if let Some(QueuedToken(mark, QueuedTokenType::Scalar(style, v))) =
            self.take_peeked_if(|token| matches!(token, QueuedTokenType::Scalar(..)))
        {
            self.pop_state();
            return Ok(Self::attach_tag_start(
                Event::Scalar(v, style, anchor_id, tag),
                mark,
                tag_start,
            ));
        }
        match *self.peeked() {
            QueuedToken(mark, QueuedTokenType::BlockEntry) if indentless_sequence => {
                self.start_block_collection(mark.start)?;
                self.skip();
                let start = (
                    Event::SequenceStart(StructureStyle::Block, anchor_id, tag),
                    mark.with_tag_start(tag_start),
                );
                let comments = match self.next_comment_events() {
                    Ok(comments) => comments,
                    Err(error)
                        if !matches!(error.kind(), ErrorKind::TooManyComments) =>
                    {
                        // `StrInput` can prove that a source has no comments and skips this
                        // lookahead, while streaming inputs must probe for one. If that probe
                        // discovers a later scanner error, the input backend must not determine
                        // whether this already-recognized sequence start is emitted first.
                        debug_assert!(self.deferred_error.is_none());
                        self.deferred_error = Some(error);
                        self.pending_empty_scalar_span = Some(mark);
                        self.state = State::IndentlessSequenceEntryNode;
                        return Ok(start);
                    }
                    Err(error) => return Err(error),
                };
                if comments.is_empty() {
                    self.pending_empty_scalar_span = Some(mark);
                    self.state = State::IndentlessSequenceEntryNode;
                    Ok(start)
                } else if let Ok(QueuedToken(
                    _,
                    QueuedTokenType::BlockEntry
                    | QueuedTokenType::Key
                    | QueuedTokenType::Value
                    | QueuedTokenType::BlockEnd,
                )) = self.peek_token()
                {
                    self.state = State::IndentlessSequenceEntry;
                    Ok(self.queue_two_events_by_span(
                        comments,
                        start,
                        (Event::empty_scalar(), mark),
                    ))
                } else {
                    self.pending_empty_scalar_span = Some(mark);
                    self.state = State::IndentlessSequenceEntryNode;
                    Ok(self.queue_event_by_span(comments, start))
                }
            }
            QueuedToken(mark, QueuedTokenType::FlowSequenceStart) => {
                self.state = State::FlowSequenceFirstEntry;
                self.skip();
                Ok(Self::attach_tag_start(
                    Event::SequenceStart(StructureStyle::Flow, anchor_id, tag),
                    mark,
                    tag_start,
                ))
            }
            QueuedToken(mark, QueuedTokenType::FlowMappingStart) => {
                self.state = State::FlowMappingFirstKey;
                self.skip();
                Ok(Self::attach_tag_start(
                    Event::MappingStart(StructureStyle::Flow, anchor_id, tag),
                    mark,
                    tag_start,
                ))
            }
            QueuedToken(mark, QueuedTokenType::BlockSequenceStart) if block => {
                self.start_block_collection(mark.start)?;
                self.state = State::BlockSequenceFirstEntry;
                self.skip();
                Ok(Self::attach_tag_start(
                    Event::SequenceStart(StructureStyle::Block, anchor_id, tag),
                    mark,
                    tag_start,
                ))
            }
            QueuedToken(mark, QueuedTokenType::BlockMappingStart) if block => {
                self.start_block_collection(mark.start)?;
                self.state = State::BlockMappingFirstKey;
                self.skip();
                Ok(Self::attach_tag_start(
                    Event::MappingStart(StructureStyle::Block, anchor_id, tag),
                    mark,
                    tag_start,
                ))
            }
            // ex 7.2, an empty scalar can follow a secondary tag
            QueuedToken(..) if tag.is_some() || anchor_id > 0 => {
                self.pop_state();
                let span = Span::empty(
                    property_end.expect("node properties record where they end"),
                );
                Ok(Self::attach_tag_start(
                    Event::empty_scalar_with_anchor(anchor_id, tag),
                    span,
                    tag_start,
                ))
            }
            QueuedToken(span, _) => {
                let kind = match self.state {
                    State::FlowSequenceFirstEntry | State::FlowSequenceEntry => {
                        ErrorKind::UnexpectedEofFlowSequence
                    }
                    State::FlowMappingFirstKey
                    | State::FlowMappingKey
                    | State::FlowMappingValue
                    | State::FlowMappingEmptyValue => {
                        ErrorKind::UnexpectedEofFlowMapping
                    }
                    State::FlowSequenceEntryMappingKey
                    | State::FlowSequenceEntryMappingValue
                    | State::FlowSequenceEntryMappingEnd
                    | State::FlowNode => ErrorKind::UnexpectedEofImplicitFlowMapping,
                    State::BlockSequenceFirstEntry
                    | State::BlockSequenceEntry
                    | State::BlockNode => ErrorKind::UnexpectedEofBlockSequence,
                    State::BlockMappingFirstKey
                    | State::BlockMappingKey
                    | State::BlockMappingValue
                    | State::BlockNodeOrIndentlessSequence => {
                        ErrorKind::UnexpectedEofBlockMapping
                    }
                    _ => ErrorKind::ExpectedNodeContent,
                };
                Err(ScanError::from_kind(span.start, kind))
            }
        }
    }

    fn block_mapping_key<'a>(&mut self, _first: bool) -> ParseResult<'a>
    where
        'input: 'a,
    {
        match *self.peeked() {
            QueuedToken(key_span, QueuedTokenType::Key) => {
                // Indentation is only meaningful for block mapping keys.
                self.pending_key_indent = Some(key_span.start.col());
                self.skip();
                if let Some(comment) = self.maybe_next_comment_event()? {
                    self.state = State::BlockMappingKeyNode;
                    return Ok(comment);
                }
                self.block_mapping_key_node()
            }
            // A missing block-mapping key before `:` is represented as an empty scalar.
            QueuedToken(mark, QueuedTokenType::Value) => {
                self.state = State::BlockMappingValue;
                Ok((Event::empty_scalar(), Span::empty(mark.start)))
            }
            QueuedToken(mark, QueuedTokenType::BlockEnd) => {
                self.end_block_collection();
                self.pop_state();
                self.skip();
                Ok((Event::MappingEnd, mark))
            }
            QueuedToken(span, _) => Err(ScanError::from_kind(
                span.start,
                ErrorKind::ExpectedBlockMappingKey,
            )),
        }
    }

    fn block_mapping_key_node<'a>(&mut self) -> ParseResult<'a>
    where
        'input: 'a,
    {
        if let QueuedToken(
            mark,
            QueuedTokenType::Key | QueuedTokenType::Value | QueuedTokenType::BlockEnd,
        ) = *self.peeked()
        {
            self.state = State::BlockMappingValue;
            Ok((Event::empty_scalar(), Span::empty(mark.start)))
        } else {
            self.defer_parse_node(
                State::BlockNodeOrIndentlessSequence,
                State::BlockMappingValue,
                true,
                true,
            )
        }
    }

    fn block_mapping_value<'a>(&mut self) -> ParseResult<'a>
    where
        'input: 'a,
    {
        match *self.peeked() {
            QueuedToken(mark, QueuedTokenType::Value) => {
                self.skip();
                let comments = self.next_comment_events()?;
                if !comments.is_empty() {
                    if let Ok(QueuedToken(
                        _,
                        QueuedTokenType::Key
                        | QueuedTokenType::Value
                        | QueuedTokenType::BlockEnd,
                    )) = self.peek_token()
                    {
                        self.state = State::BlockMappingKey;
                        return Ok(self.queue_event_by_span(
                            comments,
                            (Event::empty_scalar(), mark),
                        ));
                    }
                    self.pending_empty_scalar_span = Some(mark);
                    self.state = State::BlockMappingValueNode;
                    return Ok(self.queue_tail_and_return_first(comments));
                }
                self.block_mapping_value_node_with_empty_span(mark)
            }
            QueuedToken(mark, _) => {
                self.state = State::BlockMappingKey;
                Ok((Event::empty_scalar(), Span::empty(mark.start)))
            }
        }
    }

    fn block_mapping_value_node<'a>(&mut self) -> ParseResult<'a>
    where
        'input: 'a,
    {
        let mark = self
            .pending_empty_scalar_span
            .take()
            .expect("block mapping value-node state entered without a pending empty-scalar span");
        self.block_mapping_value_node_with_empty_span(mark)
    }

    fn block_mapping_value_node_with_empty_span<'a>(
        &mut self,
        mark: Span,
    ) -> ParseResult<'a>
    where
        'input: 'a,
    {
        if let QueuedToken(
            _,
            QueuedTokenType::Key | QueuedTokenType::Value | QueuedTokenType::BlockEnd,
        ) = *self.peek_token()?
        {
            self.state = State::BlockMappingKey;
            Ok((Event::empty_scalar(), mark))
        } else {
            self.defer_parse_node(
                State::BlockNodeOrIndentlessSequence,
                State::BlockMappingKey,
                true,
                true,
            )
        }
    }

    fn flow_mapping_key<'a>(&mut self, first: bool) -> ParseResult<'a>
    where
        'input: 'a,
    {
        let span: Span = if let QueuedToken(mark, QueuedTokenType::FlowMappingEnd) =
            *self.peeked()
        {
            mark
        } else {
            if !first {
                match *self.peeked() {
                    QueuedToken(_, QueuedTokenType::FlowEntry) => self.skip(),
                    QueuedToken(span, _) => {
                        return Err(ScanError::from_kind(
                            span.start,
                            ErrorKind::ExpectedFlowMappingSeparator,
                        ));
                    }
                }
                if let Some(comment) = self.maybe_next_comment_event()? {
                    self.state = State::FlowMappingFirstKey;
                    return Ok(comment);
                }
            }

            match *self.peeked() {
                QueuedToken(_, QueuedTokenType::Key) => {
                    self.skip();
                    if let Some(comment) = self.maybe_next_comment_event()? {
                        self.state = State::FlowMappingKeyNode;
                        return Ok(comment);
                    }
                    return self.flow_mapping_key_node();
                }
                QueuedToken(marker, QueuedTokenType::Value) => {
                    self.state = State::FlowMappingValue;
                    return Ok((Event::empty_scalar(), Span::empty(marker.start)));
                }
                QueuedToken(_, QueuedTokenType::FlowMappingEnd) => (),
                _ => {
                    return self.defer_parse_node(
                        State::FlowNode,
                        State::FlowMappingEmptyValue,
                        false,
                        false,
                    );
                }
            }

            self.peek_token()?.0
        };

        self.pop_state();
        self.skip();
        Ok((Event::MappingEnd, span))
    }

    fn flow_mapping_key_node<'a>(&mut self) -> ParseResult<'a>
    where
        'input: 'a,
    {
        if let QueuedToken(
            mark,
            QueuedTokenType::Value
            | QueuedTokenType::FlowEntry
            | QueuedTokenType::FlowMappingEnd,
        ) = *self.peeked()
        {
            self.state = State::FlowMappingValue;
            Ok((Event::empty_scalar(), Span::empty(mark.start)))
        } else {
            self.defer_parse_node(
                State::FlowNode,
                State::FlowMappingValue,
                false,
                false,
            )
        }
    }

    fn flow_mapping_value<'a>(&mut self, empty: bool) -> ParseResult<'a>
    where
        'input: 'a,
    {
        let span: Span = {
            if empty {
                let QueuedToken(mark, _) = *self.peeked();
                self.state = State::FlowMappingKey;
                return Ok((Event::empty_scalar(), Span::empty(mark.start)));
            }
            match *self.peeked() {
                QueuedToken(span, QueuedTokenType::Value) => {
                    self.skip();
                    let comments = self.next_comment_events()?;
                    if comments.is_empty() {
                        return self.flow_mapping_value_node_with_empty_span(span);
                    }
                    if let Ok(QueuedToken(
                        _,
                        QueuedTokenType::FlowEntry | QueuedTokenType::FlowMappingEnd,
                    )) = self.peek_token()
                    {
                        self.state = State::FlowMappingKey;
                        return Ok(self.queue_event_by_span(
                            comments,
                            (Event::empty_scalar(), span),
                        ));
                    }

                    self.pending_empty_scalar_span = Some(span);
                    self.state = State::FlowMappingValueNode;
                    return Ok(self.queue_tail_and_return_first(comments));
                }
                QueuedToken(marker, _) => Span::empty(marker.start),
            }
        };

        self.state = State::FlowMappingKey;
        Ok((Event::empty_scalar(), span))
    }

    fn flow_mapping_value_node<'a>(&mut self) -> ParseResult<'a>
    where
        'input: 'a,
    {
        let mark = self.pending_empty_scalar_span.take().expect(
            "flow mapping value-node state entered without a pending empty-scalar span",
        );
        self.flow_mapping_value_node_with_empty_span(mark)
    }

    fn flow_mapping_value_node_with_empty_span<'a>(
        &mut self,
        mark: Span,
    ) -> ParseResult<'a>
    where
        'input: 'a,
    {
        match self.peek_token()?.1 {
            QueuedTokenType::FlowEntry | QueuedTokenType::FlowMappingEnd => {
                self.state = State::FlowMappingKey;
                Ok((Event::empty_scalar(), mark))
            }
            _ => self.defer_parse_node(
                State::FlowNode,
                State::FlowMappingKey,
                false,
                false,
            ),
        }
    }

    fn flow_sequence_entry<'a>(&mut self, first: bool) -> ParseResult<'a>
    where
        'input: 'a,
    {
        match *self.peeked() {
            QueuedToken(mark, QueuedTokenType::FlowSequenceEnd) => {
                self.pop_state();
                self.skip();
                return Ok((Event::SequenceEnd, mark));
            }
            QueuedToken(_, QueuedTokenType::FlowEntry) if !first => {
                self.skip();
                if let Some(comment) = self.maybe_next_comment_event()? {
                    self.state = State::FlowSequenceFirstEntry;
                    return Ok(comment);
                }
            }
            QueuedToken(span, _) if !first => {
                return Err(ScanError::from_kind(
                    span.start,
                    ErrorKind::ExpectedFlowSequenceSeparator,
                ));
            }
            _ => { /* next */ }
        }
        match *self.peeked() {
            QueuedToken(mark, QueuedTokenType::FlowSequenceEnd) => {
                self.pop_state();
                self.skip();
                Ok((Event::SequenceEnd, mark))
            }
            QueuedToken(mark, QueuedTokenType::Key) => {
                self.state = State::FlowSequenceEntryMappingKey;
                self.skip();
                Ok((Event::MappingStart(StructureStyle::Flow, 0, None), mark))
            }
            _ => self.defer_parse_node(
                State::FlowNode,
                State::FlowSequenceEntry,
                false,
                false,
            ),
        }
    }

    fn indentless_sequence_entry<'a>(&mut self) -> ParseResult<'a>
    where
        'input: 'a,
    {
        match *self.peeked() {
            QueuedToken(mark, QueuedTokenType::BlockEntry) => {
                self.skip();
                let comments = self.next_comment_events()?;
                if !comments.is_empty() {
                    if let Ok(QueuedToken(
                        _,
                        QueuedTokenType::BlockEntry
                        | QueuedTokenType::Key
                        | QueuedTokenType::Value
                        | QueuedTokenType::BlockEnd,
                    )) = self.peek_token()
                    {
                        self.state = State::IndentlessSequenceEntry;
                        return Ok(self.queue_event_by_span(
                            comments,
                            (Event::empty_scalar(), mark),
                        ));
                    }
                    self.pending_empty_scalar_span = Some(mark);
                    self.state = State::IndentlessSequenceEntryNode;
                    return Ok(self.queue_tail_and_return_first(comments));
                }
                self.indentless_sequence_entry_node_with_empty_span(mark)
            }
            QueuedToken(mark, _) => {
                self.end_block_collection();
                self.pop_state();
                // The token that ends an indentless sequence belongs to the enclosing mapping
                // (`? key`, `key:`, block end); the end event is empty, at that token's start.
                Ok((Event::SequenceEnd, Span::empty(mark.start)))
            }
        }
    }

    fn indentless_sequence_entry_node<'a>(&mut self) -> ParseResult<'a>
    where
        'input: 'a,
    {
        let mark = self
            .pending_empty_scalar_span
            .take()
            .expect("indentless sequence entry-node state entered without a pending empty-scalar span");
        self.indentless_sequence_entry_node_with_empty_span(mark)
    }

    fn indentless_sequence_entry_node_with_empty_span<'a>(
        &mut self,
        mark: Span,
    ) -> ParseResult<'a>
    where
        'input: 'a,
    {
        if let QueuedToken(
            _,
            QueuedTokenType::BlockEntry
            | QueuedTokenType::Key
            | QueuedTokenType::Value
            | QueuedTokenType::BlockEnd,
        ) = *self.peek_token()?
        {
            self.state = State::IndentlessSequenceEntry;
            Ok((Event::empty_scalar(), mark))
        } else {
            self.defer_parse_node(
                State::BlockNode,
                State::IndentlessSequenceEntry,
                true,
                false,
            )
        }
    }

    fn block_sequence_entry<'a>(&mut self, _first: bool) -> ParseResult<'a>
    where
        'input: 'a,
    {
        match *self.peeked() {
            QueuedToken(mark, QueuedTokenType::BlockEnd) => {
                self.end_block_collection();
                self.pop_state();
                self.skip();
                Ok((Event::SequenceEnd, mark))
            }
            QueuedToken(mark, QueuedTokenType::BlockEntry) => {
                self.skip();
                let comments = self.next_comment_events()?;
                if !comments.is_empty() {
                    if let Ok(QueuedToken(
                        _,
                        QueuedTokenType::BlockEntry | QueuedTokenType::BlockEnd,
                    )) = self.peek_token()
                    {
                        self.state = State::BlockSequenceEntry;
                        return Ok(self.queue_event_by_span(
                            comments,
                            (Event::empty_scalar(), mark),
                        ));
                    }
                    self.pending_empty_scalar_span = Some(mark);
                    self.state = State::BlockSequenceEntryNode;
                    return Ok(self.queue_tail_and_return_first(comments));
                }
                self.block_sequence_entry_node_with_empty_span(mark)
            }
            QueuedToken(span, _) => Err(ScanError::from_kind(
                span.start,
                ErrorKind::ExpectedBlockSequenceEntry,
            )),
        }
    }

    fn block_sequence_entry_node<'a>(&mut self) -> ParseResult<'a>
    where
        'input: 'a,
    {
        let mark = self
            .pending_empty_scalar_span
            .take()
            .expect("block sequence entry-node state entered without a pending empty-scalar span");
        self.block_sequence_entry_node_with_empty_span(mark)
    }

    fn block_sequence_entry_node_with_empty_span<'a>(
        &mut self,
        mark: Span,
    ) -> ParseResult<'a>
    where
        'input: 'a,
    {
        if let QueuedToken(_, QueuedTokenType::BlockEntry | QueuedTokenType::BlockEnd) =
            *self.peek_token()?
        {
            self.state = State::BlockSequenceEntry;
            Ok((Event::empty_scalar(), mark))
        } else {
            self.defer_parse_node(
                State::BlockNode,
                State::BlockSequenceEntry,
                true,
                false,
            )
        }
    }

    fn flow_sequence_entry_mapping_key<'a>(&mut self) -> ParseResult<'a>
    where
        'input: 'a,
    {
        if let QueuedToken(
            mark,
            QueuedTokenType::FlowEntry | QueuedTokenType::FlowSequenceEnd,
        ) = *self.peeked()
        {
            self.state = State::FlowSequenceEntryMappingValue;
            Ok((Event::empty_scalar(), Span::empty(mark.start)))
        } else {
            self.defer_parse_node(
                State::FlowNode,
                State::FlowSequenceEntryMappingValue,
                false,
                false,
            )
        }
    }

    fn flow_sequence_entry_mapping_value<'a>(&mut self) -> ParseResult<'a>
    where
        'input: 'a,
    {
        match *self.peeked() {
            QueuedToken(_, QueuedTokenType::Value) => {
                self.skip();
                if let Some(comment) = self.maybe_next_comment_event()? {
                    self.state = State::FlowSequenceEntryMappingValueNode;
                    return Ok(comment);
                }
                self.flow_sequence_entry_mapping_value_node()
            }
            QueuedToken(mark, _) => {
                self.state = State::FlowSequenceEntryMappingEnd;
                Ok((Event::empty_scalar(), Span::empty(mark.start)))
            }
        }
    }

    fn flow_sequence_entry_mapping_value_node<'a>(&mut self) -> ParseResult<'a>
    where
        'input: 'a,
    {
        let QueuedToken(span, ref tok) = *self.peeked();
        if matches!(
            tok,
            QueuedTokenType::FlowEntry | QueuedTokenType::FlowSequenceEnd
        ) {
            self.state = State::FlowSequenceEntryMappingEnd;
            Ok((Event::empty_scalar(), Span::empty(span.start)))
        } else {
            self.defer_parse_node(
                State::FlowNode,
                State::FlowSequenceEntryMappingEnd,
                false,
                false,
            )
        }
    }

    #[allow(clippy::unnecessary_wraps)]
    fn flow_sequence_entry_mapping_end<'a>(&mut self) -> ParseResult<'a>
    where
        'input: 'a,
    {
        self.state = State::FlowSequenceEntry;
        let QueuedToken(span, _) = *self.peeked();
        Ok((Event::MappingEnd, Span::empty(span.start)))
    }

    /// Resolve a tag from the handle and the suffix.
    fn resolve_tag(
        &self,
        span: Span,
        handle: &Cow<'input, str>,
        suffix: Cow<'input, str>,
    ) -> Result<Cow<'input, Tag>, ScanError> {
        let original_handle = handle.to_string();
        let suffix = suffix.into_owned();
        let tag = if handle == "!!" {
            // "!!" is a shorthand for "tag:yaml.org,2002:". However, that default can be
            // overridden.
            Tag::with_original_handle(
                self.tags.get("!!").map_or_else(
                    || "tag:yaml.org,2002:".to_string(),
                    ToString::to_string,
                ),
                suffix,
                original_handle,
            )
        } else if handle.is_empty() && suffix == "!" {
            // Bare "!" is a non-specific tag, not a primary handle to expand with %TAG.
            Tag::with_original_handle(String::new(), suffix, original_handle)
        } else {
            // Lookup handle in our tag directives.
            let prefix = self.tags.get(&**handle);
            if let Some(prefix) = prefix {
                Tag::with_original_handle(prefix.to_string(), suffix, original_handle)
            } else {
                // Otherwise, it may be a local handle. With a local handle, the handle is set to
                // "!" and the suffix to whatever follows it ("!foo" -> ("!", "foo")).
                // If the handle is of the form "!foo!", this cannot be a local handle and we need
                // to error.
                if handle.len() >= 2 && handle.starts_with('!') && handle.ends_with('!')
                {
                    return Err(ScanError::from_kind(
                        span.start,
                        ErrorKind::UndeclaredTagHandle,
                    ));
                }
                Tag::with_original_handle(handle.to_string(), suffix, original_handle)
            }
        };
        Ok(Cow::Owned(tag))
    }
}

impl<'input, T: BorrowedInput<'input>, O: crate::TokenObserver> ParserTrait<'input>
    for Parser<'input, T, O>
{
    fn peek(&mut self) -> Option<Result<&(Event<'input>, Span), ScanError>> {
        if let Some(ref x) = self.current {
            Some(Ok(x))
        } else if let Some(error) = &self.current_error {
            Some(Err(error.clone()))
        } else {
            if self.stream_end_emitted {
                return None;
            }
            match self.next_event_impl() {
                Ok(token) => self.current = Some(token),
                Err(error) => {
                    self.current_error = Some(error.clone());
                    return Some(Err(error));
                }
            }
            self.current.as_ref().map(Ok)
        }
    }

    fn next_event(&mut self) -> Option<ParseResult<'input>> {
        if let Some(error) = self.current_error.take() {
            self.stream_end_emitted = true;
            return Some(Err(error));
        }

        if self.stream_end_emitted {
            return None;
        }

        let tok = self.next_event_impl();
        if matches!(tok, Ok((Event::StreamEnd, _)) | Err(_)) {
            self.stream_end_emitted = true;
        }
        Some(tok)
    }

    fn load<R: SpannedEventReceiver<'input>>(
        &mut self,
        recv: &mut R,
        multi: bool,
    ) -> Result<(), ScanError> {
        let mut recv = InfallibleSpannedReceiver(recv);
        into_scan_result(ParserTrait::try_load(self, &mut recv, multi))
    }

    fn try_load<R: TrySpannedEventReceiver<'input>>(
        &mut self,
        recv: &mut R,
        multi: bool,
    ) -> Result<(), TryLoadError<R::Error>> {
        let stream_start_buffered =
            matches!(self.current.as_ref(), Some((Event::StreamStart, _)));
        if !self.scanner.stream_started() || stream_start_buffered {
            let (ev, span) = self.next_event_impl()?;
            try_emit(recv, ev, span)?;
        }

        let has_buffered_result =
            self.current.is_some() || self.current_error.is_some();
        let has_buffered_result = has_buffered_result
            || self.deferred_error.is_some()
            || !self.queued_events.is_empty();
        if self.scanner.stream_ended() && !has_buffered_result {
            // The scanner has already reached EOF before the document loop, so emit the terminal
            // event and stop.
            try_emit(recv, Event::StreamEnd, Span::empty(self.scanner.mark()))?;
            self.stream_end_emitted = true;
            return Ok(());
        }

        loop {
            let (ev, span) = if let Some(error) = self.current_error.take() {
                self.stream_end_emitted = true;
                return Err(TryLoadError::scan(error));
            } else {
                self.next_event_impl()?
            };
            let is_doc_end = matches!(ev, Event::DocumentEnd);
            let is_stream_end = matches!(ev, Event::StreamEnd);

            try_emit(recv, ev, span)?;

            if is_stream_end {
                self.stream_end_emitted = true;
                return Ok(());
            }
            if !multi && is_doc_end {
                return Ok(());
            }
        }
    }
}

impl<'input, T: BorrowedInput<'input>, O: crate::TokenObserver> Iterator
    for Parser<'input, T, O>
{
    type Item = Result<(Event<'input>, Span), ScanError>;

    fn next(&mut self) -> Option<Self::Item> {
        self.next_event()
    }
}

impl<'input, T: BorrowedInput<'input>, O: crate::TokenObserver>
    core::iter::FusedIterator for Parser<'input, T, O>
{
}
